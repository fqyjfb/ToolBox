// scripts/write-env-secrets.cjs
// 用途：CI / 本地构建 Electron 安装包前执行，将密钥注入为打包产物可读取的形式。
// 输出：electron/lib/env-secrets.cjs（已加入 .gitignore，永不进仓库）
// 仅当对应环境变量存在时才写入，保持字段与 emailOAuthService.cjs 中的 process.env 读取一致。
//
// 优先级（由高到低）：
//   1) Node 进程的 process.env（CI 场景：GitHub Actions 通过 env 注入）
//   2) 项目根目录的 .env 文件（本地构建场景：开发者手动填写密钥）
//
// 用法：
//   本地构建：在 .env 填好密钥后，运行 `pnpm electron:build`（本脚本已嵌入到该命令前置步骤）
//   CI 构建：在 workflow 的 env 中声明对应 secrets，后续步骤自动生效

const fs = require('fs');
const path = require('path');

const SECRET_KEYS = [
  'GOOGLE_OAUTH_CLIENT_ID',
  'GOOGLE_OAUTH_CLIENT_SECRET',
  'OUTLOOK_OAUTH_CLIENT_ID',
  'OUTLOOK_OAUTH_CLIENT_SECRET',
];

const projectRoot = path.resolve(__dirname, '..');
const envFile = path.join(projectRoot, '.env');

// 兜底：从 .env 读取，仅在 process.env 中对应键为空时才补全
function loadDotenvFallback() {
  if (!fs.existsSync(envFile)) return;
  let raw;
  try {
    raw = fs.readFileSync(envFile, 'utf8');
  } catch {
    return;
  }
  for (const line of raw.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const idx = trimmed.indexOf('=');
    if (idx === -1) continue;
    const key = trimmed.slice(0, idx).trim();
    let value = trimmed.slice(idx + 1).trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    if (SECRET_KEYS.includes(key) && (process.env[key] == null || process.env[key] === '')) {
      process.env[key] = value;
    }
  }
}

loadDotenvFallback();

const outDir = path.join(projectRoot, 'electron', 'lib');
const outFile = path.join(outDir, 'env-secrets.cjs');

const obj = {};
for (const k of SECRET_KEYS) {
  const v = process.env[k];
  if (typeof v === 'string' && v.length > 0) {
    obj[k] = v;
  }
}

// 确保目录存在
fs.mkdirSync(outDir, { recursive: true });

const lines = [];
lines.push('// Auto-generated by scripts/write-env-secrets.cjs');
lines.push('// 本文件由构建前步骤生成：CI 来自 GitHub Environments Secrets；本地构建来自 .env');
lines.push('// 请勿手动修改或提交到版本库（已加入 .gitignore）');
lines.push('');
lines.push('module.exports = {');
for (const [k, v] of Object.entries(obj)) {
  lines.push(`  ${k}: ${JSON.stringify(v)},`);
}
lines.push('};');
lines.push('');

fs.writeFileSync(outFile, lines.join('\n'), 'utf8');

const injected = Object.keys(obj).join(', ') || '(none)';
console.log(`[write-env-secrets] wrote ${outFile} (injected: ${injected})`);
